/**
 * UNIT — typed/validate.ts: the checks { validate: true } derives from a table definition.
 * No database: each column kind, each size rule, and each update operator.
 */
import { describe, it, expect } from "bun:test";
import { defineTable, t, MiraValidationError } from "../../src";
import { validateInsert, validateUpdate, checkValue } from "../../src/typed/validate";

const T = defineTable("V", {
  ID: t.id(),
  N: t.number(),
  INT: t.number(3),
  MONEY: t.money(),
  DEC: t.decimal(5, 2).nullable(),
  NAME: t.text(4),
  CHARS: t.text(4, "char").nullable(),
  FIXED: t.char(2).nullable(),
  BODY: t.clob().nullable(),
  PIC: t.blob().nullable(),
  ON: t.date().nullable(),
  AT: t.timestampTz().nullable(),
  DOC: t.json<{ a: number }>().nullable(),
  RAW: t.raw<number>("BINARY_DOUBLE").nullable(),
  STATUS: t.text(10).default("'open'"),
});
const cols = T.columns;
const issues = (fn: () => void) => {
  try {
    fn();
    return [];
  } catch (e) {
    expect(e).toBeInstanceOf(MiraValidationError);
    return (e as MiraValidationError).issues.map((i) => `${i.column}: ${i.message}`);
  }
};
const ok = { N: 1.5, INT: 12, MONEY: "12.3400", NAME: "abcd" };

describe("unit/validate: values by column kind", () => {
  it("NUMBER: finite; whole when the scale is 0; integer digits within the precision; decimal strings for a scale", () => {
    const m = (type: string) => ({ type, nullable: false, identity: false, primaryKey: false });
    expect(checkValue(m("NUMBER"), 1e300)).toBeNull();
    expect(checkValue(m("NUMBER"), Infinity)).toBe("must be a finite number, got Infinity");
    expect(checkValue(m("NUMBER"), "1")).toBe('must be a number, got the string "1"');
    expect(checkValue(m("NUMBER(3)"), 999)).toBeNull();
    expect(checkValue(m("NUMBER(3)"), -1000)).toBe("has 4 digits before the decimal point; NUMBER(3) allows 3");
    expect(checkValue(m("NUMBER(3,0)"), 1.5)).toBe("must be a whole number, got 1.5");
    expect(checkValue(m("NUMBER(5,2)"), "-123.456")).toBeNull(); // Oracle rounds the extra scale
    expect(checkValue(m("NUMBER(5,2)"), "+0001.5")).toBeNull();
    expect(checkValue(m("NUMBER(5,2)"), ".5")).toBeNull();
    expect(checkValue(m("NUMBER(5,2)"), 1234.5)).toBe("has 4 digits before the decimal point; NUMBER(5,2) allows 3");
    expect(checkValue(m("NUMBER(5,2)"), "1e3")).toBe('must be a decimal number, got "1e3"');
    expect(checkValue(m("NUMBER(5,2)"), true)).toBe("must be a number or a decimal string, got boolean true");
    expect(checkValue(m("NUMBER(2,4)"), 0.001)).toBeNull(); // scale above precision: no integer digits allowed
    expect(checkValue(m("NUMBER(2,4)"), 1)).toBe("has 1 digits before the decimal point; NUMBER(2,4) allows 0");
    expect(checkValue(m("NUMBER(38)"), 1e25)).toBeNull(); // exponent form: Oracle checks it
  });

  it("text: a string within VARCHAR2(n) bytes (UTF-8) or n CHAR characters; CHAR(n); CLOB", () => {
    expect(issues(() => validateInsert("V", cols, { ...ok, NAME: "ñaña" }))).toEqual(["NAME: is 6 bytes long; VARCHAR2(4) allows 4"]);
    expect(issues(() => validateInsert("V", cols, { ...ok, CHARS: "ñaña" }))).toEqual([]);
    expect(issues(() => validateInsert("V", cols, { ...ok, CHARS: "ñañas" }))).toEqual(["CHARS: is 5 characters long; VARCHAR2(4 CHAR) allows 4"]);
    expect(issues(() => validateInsert("V", cols, { ...ok, FIXED: "abc", NAME: 5 }))).toEqual(["NAME: must be a string, got number 5", "FIXED: is 3 bytes long; CHAR(2) allows 2"]);
    expect(issues(() => validateInsert("V", cols, { ...ok, BODY: ["x"] }))).toEqual(["BODY: must be a string, got an array"]);
  });

  it("binary, dates, JSON and raw types", () => {
    expect(issues(() => validateInsert("V", cols, { ...ok, PIC: Buffer.from([1]), ON: new Date(), AT: new Date(0), DOC: { a: 1 }, RAW: 1.5 }))).toEqual([]);
    expect(issues(() => validateInsert("V", cols, { ...ok, PIC: "x", ON: "2026-01-01", AT: new Date("nope") }))).toEqual([
      'PIC: must be a Buffer, got the string "x"',
      'ON: must be a Date, got the string "2026-01-01"',
      "AT: must be a valid Date, got an invalid one",
    ]);
    expect(issues(() => validateInsert("V", cols, { ...ok, MONEY: new Date(0), INT: Buffer.from([]), N: {} }))).toEqual([
      "N: must be a number, got an object",
      "INT: must be a number, got a Buffer",
      "MONEY: must be a number or a decimal string, got a Date",
    ]);
  });
});

describe("unit/validate: inserts", () => {
  it("required, nullable, generated, unknown and undefined columns", () => {
    expect(issues(() => validateInsert("V", cols, { ...ok, DEC: null, CHARS: undefined }))).toEqual([]);
    // GENERATED BY DEFAULT AS IDENTITY: not required, and an insert may give it.
    const byDefault = defineTable("V2", { K: t.number(5).identityByDefault(), A: t.text(1) }).columns;
    expect(issues(() => validateInsert("V2", byDefault, { A: "a" }))).toEqual([]);
    expect(issues(() => validateInsert("V2", byDefault, { K: 3, A: "a" }))).toEqual([]);
    expect(issues(() => validateInsert("V", cols, { ID: 1, NAME: null, X: 1 }))).toEqual([
      "ID: is generated by Oracle and cannot be set",
      "NAME: cannot be null",
      "X: is not a column of this table",
      "N: is required",
      "INT: is required",
      "MONEY: is required",
    ]);
  });

  it("the error message names the table and every problem", () => {
    expect(() => validateInsert("V", cols, { ...ok, NAME: null })).toThrow("[V] insert is not valid: NAME cannot be null.");
    const err = new MiraValidationError("V", "insert", [{ column: "A", message: "x" }]);
    expect([err.name, Object.isFrozen(err.issues), Object.isFrozen(err.issues[0])]).toEqual(["MiraValidationError", true, true]);
  });
});

describe("unit/validate: updates", () => {
  it("$set / $min / $max values, $unset of a non-nullable column, $inc / $mul numbers", () => {
    expect(issues(() => validateUpdate("V", cols, { $set: { NAME: "ok", DEC: null, CHARS: undefined }, $inc: { N: 1 }, $mul: { INT: 2 }, $min: { MONEY: 1 }, $unset: { BODY: 1 } }))).toEqual([]);
    expect(issues(() => validateUpdate("V", cols, { $set: { NAME: null, ID: 2 }, $max: { INT: 1.5 }, $unset: { STATUS: 1 }, $inc: { N: "1" }, $mul: { INT: NaN } }))).toEqual([
      "NAME: cannot be null",
      "ID: is generated by Oracle and cannot be set",
      "INT: must be a whole number, got 1.5",
      "STATUS: cannot be unset: it is not nullable",
      'N: $inc needs a finite number, got the string "1"',
      "INT: $mul needs a finite number, got number NaN",
    ]);
  });

  it("JSON paths, $push / $pull / $rename and $currentDate are left alone; unknown columns are not", () => {
    expect(issues(() => validateUpdate("V", cols, { $set: { "DOC.a": "anything" }, $push: { "DOC.list": 1 }, $pull: { "DOC.list": 2 }, $rename: { NAME: "X" }, $currentDate: { AT: true }, $weird: 5 }))).toEqual([]);
    expect(issues(() => validateUpdate("V", cols, { $set: { "NAME.x": 1, NOPE: 1 } }))).toEqual(["NAME.x: is not a column of this table", "NOPE: is not a column of this table"]);
    expect(() => validateUpdate("V", cols, { $set: { NOPE: 1 } })).toThrow("[V] update is not valid: NOPE is not a column of this table.");
  });
});
