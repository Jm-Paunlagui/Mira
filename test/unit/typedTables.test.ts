/**
 * UNIT — typed tables (Mira 2.1): column builders, defineTable(), ddl(), on(),
 * and the type generator against a stub catalogue. No database round trip.
 * The compile-time side is tested in test/types/typedTables.types.ts.
 */
import { describe, it, expect } from "bun:test";
import { defineTable, t, TypedTable, generateTableTypes, createDb, OracleCollection, QueryBuilder } from "../../src/utils/oracle-mongo-wrapper";
import { exportName } from "../../src/utils/oracle-mongo-wrapper/typed/generate";

const db = createDb("appDb");

describe("unit: column builders", () => {
  it("each builder's Oracle type", () => {
    expect(t.number().meta.type).toBe("NUMBER");
    expect(t.number(10).meta.type).toBe("NUMBER(10)");
    expect(t.number(10, 0).meta.type).toBe("NUMBER(10,0)");
    expect(t.number(12, 2).meta.type).toBe("NUMBER(12,2)");
    expect(t.money().meta.type).toBe("NUMBER(19,4)");
    expect(t.decimal(9, 6).meta.type).toBe("NUMBER(9,6)");
    expect(t.text(100).meta.type).toBe("VARCHAR2(100)");
    expect(t.text(100, "char").meta.type).toBe("VARCHAR2(100 CHAR)");
    expect(t.text(100, "byte").meta.type).toBe("VARCHAR2(100)");
    expect(t.char(2).meta.type).toBe("CHAR(2)");
    expect(t.clob().meta.type).toBe("CLOB");
    expect(t.blob().meta.type).toBe("BLOB");
    expect(t.date().meta.type).toBe("DATE");
    expect(t.timestamp().meta.type).toBe("TIMESTAMP");
    expect(t.timestamp(0).meta.type).toBe("TIMESTAMP(0)");
    expect(t.timestamp(3).meta.type).toBe("TIMESTAMP(3)");
    expect(t.timestampTz().meta.type).toBe("TIMESTAMP WITH TIME ZONE");
    expect(t.timestampTz(0).meta.type).toBe("TIMESTAMP(0) WITH TIME ZONE");
    expect(t.timestampTz(9).meta.type).toBe("TIMESTAMP(9) WITH TIME ZONE");
    expect(t.raw<number>("BINARY_DOUBLE").meta.type).toBe("BINARY_DOUBLE");
  });

  it("t.id() is an identity primary key", () => {
    expect(t.id().meta).toEqual({ type: "NUMBER", nullable: false, identity: true, primaryKey: true });
  });

  it("modifiers return a new column; the original is unchanged and frozen", () => {
    const base = t.text(10);
    const n = base.nullable().default("'x'").check("C IS NOT NULL").references("T", "C");
    expect(base.meta).toEqual({ type: "VARCHAR2(10)", nullable: false, identity: false, primaryKey: false });
    expect(n.meta).toEqual({ type: "VARCHAR2(10)", nullable: true, default: "'x'", identity: false, primaryKey: false, check: "C IS NOT NULL", references: { table: "T", column: "C" } });
    expect(Object.isFrozen(n.meta)).toBe(true);
    expect(t.number().identityByDefault().meta.type).toBe("NUMBER GENERATED BY DEFAULT AS IDENTITY");
    expect(t.text(5).nullable().primaryKey().meta.nullable).toBe(false); // a primary key is NOT NULL
  });

  it("references() takes a table definition too", () => {
    const Parents = defineTable("PARENTS", { ID: t.id() });
    expect(t.number().references(Parents, "ID").meta.references).toEqual({ table: "PARENTS", column: "ID" });
  });

  it("refuses sizes that would emit odd DDL", () => {
    expect(() => t.text(0)).toThrow(/positive integer/);
    expect(() => t.text(1.5)).toThrow(/positive integer/);
    expect(() => t.char(-1)).toThrow(/positive integer/);
    expect(() => t.number(0)).toThrow(/positive integer/);
    expect(() => t.number(5, 6)).toThrow(/scale/);
    expect(() => t.number(5, -1)).toThrow(/scale/);
    expect(() => t.number(5, 1.5)).toThrow(/scale/);
    expect(() => t.decimal(5, 0)).toThrow(/positive integer/);
    expect(() => t.timestamp(-1)).toThrow(/positive integer/);
    expect(() => t.timestampTz(1.5)).toThrow(/positive integer/);
  });
});

describe("unit: defineTable", () => {
  const Orders = defineTable("ORDERS", {
    ID: t.id(),
    CUSTOMER_ID: t.number().references("CUSTOMERS", "ID"),
    TOTAL: t.money().check("TOTAL >= 0"),
    NOTE: t.text(400).nullable(),
    STATUS: t.text(10).default("'open'"),
  });

  it("keeps its name and frozen columns", () => {
    expect(Orders).toBeInstanceOf(TypedTable);
    expect(Orders.name).toBe("ORDERS");
    expect(Object.keys(Orders.columns)).toEqual(["ID", "CUSTOMER_ID", "TOTAL", "NOTE", "STATUS"]);
    expect(Object.isFrozen(Orders.columns)).toBe(true);
  });

  it("ddl() is the createTable() column spec", () => {
    expect(Orders.ddl()).toEqual({
      ID: { type: "NUMBER", autoIncrement: true, primaryKey: true },
      CUSTOMER_ID: { type: "NUMBER", notNull: true, references: { table: "CUSTOMERS", column: "ID" } },
      TOTAL: { type: "NUMBER(19,4)", notNull: true, check: "TOTAL >= 0" },
      NOTE: { type: "VARCHAR2(400)" },
      STATUS: { type: "VARCHAR2(10)", notNull: true, default: "'open'" },
    });
    expect(defineTable("SEQS", { SEQ: t.number().identity() }).ddl()).toEqual({ SEQ: { type: "NUMBER", autoIncrement: true, notNull: true } });
  });

  it("refuses a bad name or column map", () => {
    expect(() => defineTable("", { A: t.number() })).toThrow(/non-empty string/);
    expect(() => defineTable("  ", { A: t.number() })).toThrow(/non-empty string/);
    expect(() => defineTable(42 as never, { A: t.number() })).toThrow(/non-empty string/);
    expect(() => defineTable("X", {})).toThrow(/at least one column/);
    expect(() => defineTable("X", undefined as never)).toThrow(/at least one column/);
    expect(() => defineTable("X", { A: "NUMBER" } as never)).toThrow(/column builder/);
    expect(() => defineTable("X", { A: null } as never)).toThrow(/column builder/);
    expect(() => defineTable("X", { A: t.id(), B: t.number().identity() })).toThrow(/one identity column.*A, B/);
    expect(() => defineTable("X", { A: t.id(), B: t.number().identityByDefault() })).toThrow(/ORA-30669/);
  });

  it("on(db) is the plain OracleCollection; on(session) asks the session", () => {
    const c = Orders.on(db);
    expect(c).toBeInstanceOf(OracleCollection);
    expect(c.tableName).toBe("ORDERS");
    expect(c.untyped).toBe(c as unknown as OracleCollection);
    const q = c.find({ STATUS: "open" });
    expect(q).toBeInstanceOf(QueryBuilder);
    expect(q.untyped).toBe(q as unknown as QueryBuilder);
    const asked: string[] = [];
    const session = { collection: (n: string) => (asked.push(n), new OracleCollection(n, db)) };
    expect(Orders.on(session).tableName).toBe("ORDERS");
    expect(asked).toEqual(["ORDERS"]);
  });

  it("a typed find() builds the same SQL as the untyped one", () => {
    const typed = Orders.on(db).find({ TOTAL: { $gt: 100 }, NOTE: null }).sort({ ID: -1 }).project({ ID: 1 }).untyped._buildSQL();
    const plain = new OracleCollection("ORDERS", db).find({ TOTAL: { $gt: 100 }, NOTE: null }).sort({ ID: -1 }).project({ ID: 1 })._buildSQL();
    expect(typed.sql).toBe(plain.sql);
  });
});

describe("unit: generateTableTypes (stub catalogue)", () => {
  type Row = Record<string, unknown>;
  const col = (over: Row): Row => ({
    TABLE_NAME: "T_ALL", COLUMN_NAME: "C", DATA_TYPE: "VARCHAR2", DATA_LENGTH: 10, CHAR_LENGTH: 10, CHAR_USED: "B",
    DATA_PRECISION: null, DATA_SCALE: null, NULLABLE: "N", DATA_DEFAULT: null, IDENTITY_COLUMN: "NO", GENERATION_TYPE: null,
    IS_PK: 0, REF_TABLE: null, REF_COLUMN: null, ...over,
  });
  const stub = (rows: Row[], seen: { sql?: string; binds?: unknown; opts?: unknown } = {}) =>
    ({
      oracledb: { OUT_FORMAT_OBJECT: 4002, STRING: 2001 },
      withConnection: async (cb: (c: unknown) => unknown) =>
        cb({ execute: async (sql: string, binds: unknown, opts: unknown) => (Object.assign(seen, { sql, binds, opts }), { rows }) }),
    }) as never;

  it("maps every Oracle type, flag and key", async () => {
    const rows = [
      col({ COLUMN_NAME: "ID", DATA_TYPE: "NUMBER", IDENTITY_COLUMN: "YES", GENERATION_TYPE: "ALWAYS", IS_PK: 1 }),
      col({ COLUMN_NAME: "N", DATA_TYPE: "NUMBER" }),
      col({ COLUMN_NAME: "I", DATA_TYPE: "NUMBER", DATA_SCALE: 0 }),
      col({ COLUMN_NAME: "P", DATA_TYPE: "NUMBER", DATA_PRECISION: 10, DATA_SCALE: 0 }),
      col({ COLUMN_NAME: "P2", DATA_TYPE: "NUMBER", DATA_PRECISION: 5, DATA_SCALE: null }),
      col({ COLUMN_NAME: "M", DATA_TYPE: "NUMBER", DATA_PRECISION: 19, DATA_SCALE: 4 }),
      col({ COLUMN_NAME: "D", DATA_TYPE: "NUMBER", DATA_PRECISION: 9, DATA_SCALE: 6, NULLABLE: "Y" }),
      col({ COLUMN_NAME: "V", DATA_TYPE: "VARCHAR2", DATA_LENGTH: 100, DATA_DEFAULT: "'open' \n" }),
      col({ COLUMN_NAME: "VC", DATA_TYPE: "VARCHAR2", DATA_LENGTH: 400, CHAR_LENGTH: 100, CHAR_USED: "C" }),
      col({ COLUMN_NAME: "CH", DATA_TYPE: "CHAR", DATA_LENGTH: 2 }),
      col({ COLUMN_NAME: "CHC", DATA_TYPE: "CHAR", DATA_LENGTH: 8, CHAR_LENGTH: 2, CHAR_USED: "C" }),
      col({ COLUMN_NAME: "NV", DATA_TYPE: "NVARCHAR2", DATA_LENGTH: 40, CHAR_LENGTH: 20, CHAR_USED: "C" }),
      col({ COLUMN_NAME: "CL", DATA_TYPE: "CLOB", NULLABLE: "Y" }),
      col({ COLUMN_NAME: "NCL", DATA_TYPE: "NCLOB", NULLABLE: "Y" }),
      col({ COLUMN_NAME: "BL", DATA_TYPE: "BLOB", NULLABLE: "Y" }),
      col({ COLUMN_NAME: "RW", DATA_TYPE: "RAW", DATA_LENGTH: 16 }),
      col({ COLUMN_NAME: "DT", DATA_TYPE: "DATE", DATA_DEFAULT: "NULL" }),
      col({ COLUMN_NAME: "TS", DATA_TYPE: "TIMESTAMP(6)", DATA_DEFAULT: "SYSTIMESTAMP" }),
      col({ COLUMN_NAME: "TS3", DATA_TYPE: "TIMESTAMP(3)" }),
      col({ COLUMN_NAME: "TZ", DATA_TYPE: "TIMESTAMP(6) WITH TIME ZONE" }),
      col({ COLUMN_NAME: "TZ0", DATA_TYPE: "TIMESTAMP(0) WITH TIME ZONE" }),
      col({ COLUMN_NAME: "TL", DATA_TYPE: "TIMESTAMP(6) WITH LOCAL TIME ZONE" }),
      col({ COLUMN_NAME: "F", DATA_TYPE: "BINARY_DOUBLE" }),
      col({ COLUMN_NAME: "J", DATA_TYPE: "JSON", NULLABLE: "Y" }),
      col({ COLUMN_NAME: "JT", DATA_TYPE: "CLOB", IS_JSON: 1 }),
      col({ COLUMN_NAME: "SEQ", DATA_TYPE: "NUMBER", IDENTITY_COLUMN: "YES", GENERATION_TYPE: "BY DEFAULT" }),
      col({ COLUMN_NAME: "SEQ2", DATA_TYPE: "NUMBER", DATA_PRECISION: 10, IDENTITY_COLUMN: "YES", GENERATION_TYPE: "ALWAYS" }),
      col({ COLUMN_NAME: "FK", DATA_TYPE: "NUMBER", NULLABLE: "Y", REF_TABLE: "PARENT", REF_COLUMN: "ID" }),
      col({ COLUMN_NAME: "lower case", DATA_TYPE: "DATE", DATA_DEFAULT: "  " }),
      col({ TABLE_NAME: "9LIVES", COLUMN_NAME: "K", DATA_TYPE: "VARCHAR2", DATA_LENGTH: 3, IS_PK: 1, NULLABLE: "N" }),
    ];
    const code = await generateTableTypes(stub(rows), { importFrom: "./mira" });
    const lines = code.split("\n");
    const at = (c: string) => lines.find((l) => l.trimStart().startsWith(`${c}:`) || l.trimStart().startsWith(`"${c}":`))?.trim();
    expect(lines[2]).toBe('import { defineTable, t } from "./mira";');
    expect(code).toContain('export const TAll = defineTable("T_ALL", {');
    expect(code).toContain("export type TAllRow = typeof TAll.$row;");
    expect(at("ID")).toBe("ID: t.id(),");
    expect(at("N")).toBe("N: t.number(),");
    expect(at("I")).toBe('I: t.raw<number>("NUMBER(*,0)"),');
    expect(at("P")).toBe("P: t.number(10),");
    expect(at("P2")).toBe("P2: t.number(5),");
    expect(at("M")).toBe("M: t.money(),");
    expect(at("D")).toBe("D: t.decimal(9, 6).nullable(),");
    expect(at("V")).toBe(`V: t.text(100).default("'open'"),`);
    expect(at("VC")).toBe('VC: t.text(100, "char"),');
    expect(at("CH")).toBe("CH: t.char(2),");
    expect(at("CHC")).toBe('CHC: t.raw<string>("CHAR(2 CHAR)"),');
    expect(at("NV")).toBe('NV: t.raw<string>("NVARCHAR2(20)"),');
    expect(at("CL")).toBe("CL: t.clob().nullable(),");
    expect(at("NCL")).toBe('NCL: t.raw<string>("NCLOB").nullable(),');
    expect(at("BL")).toBe("BL: t.blob().nullable(),");
    expect(at("RW")).toBe('RW: t.raw<Buffer>("RAW(16)"),');
    expect(at("DT")).toBe("DT: t.date(),");
    expect(at("TS")).toBe('TS: t.timestamp().default("SYSTIMESTAMP"),');
    expect(at("TS3")).toBe("TS3: t.timestamp(3),");
    expect(at("TZ")).toBe("TZ: t.timestampTz(),");
    expect(at("TZ0")).toBe("TZ0: t.timestampTz(0),");
    expect(at("TL")).toBe('TL: t.raw<Date>("TIMESTAMP(6) WITH LOCAL TIME ZONE"),');
    expect(at("F")).toBe('F: t.raw<number>("BINARY_DOUBLE"),');
    expect(at("J")).toBe("J: t.json({ native: true }).nullable(),");
    expect(at("JT")).toBe("JT: t.json(),");
    expect(at("SEQ")).toBe("SEQ: t.number().identityByDefault(),");
    expect(at("SEQ2")).toBe("SEQ2: t.number(10).identity(),");
    expect(at("FK")).toBe('FK: t.number().nullable().references("PARENT", "ID"),');
    expect(at("lower case")).toBe('"lower case": t.date(),');
    expect(code).toContain('export const T9lives = defineTable("9LIVES", {');
    expect(at("K")).toBe("K: t.text(3).primaryKey(),");
  });

  it("filters tables: exact names with =, patterns with LIKE; default import and empty result", async () => {
    const seen: { sql?: string; binds?: unknown; opts?: unknown } = {};
    const code = await generateTableTypes(stub([], seen), { tables: ["SIM_ORDERS", "SIM_%"] });
    expect(seen.sql).toContain("ut.TABLE_NAME = :t0 OR ut.TABLE_NAME LIKE :t1");
    expect(seen.binds).toEqual({ t0: "SIM_ORDERS", t1: "SIM_%" });
    expect(seen.opts).toEqual({ outFormat: 4002, fetchInfo: { DATA_DEFAULT: { type: 2001 } } });
    expect(code).toContain('from "@jm-paunlagui/mira";');
    expect(code).not.toContain("defineTable(\"");
    const all: { sql?: string } = {};
    await generateTableTypes(stub([], all));
    expect(all.sql).not.toContain(":t0");
    const noRows = { oracledb: { OUT_FORMAT_OBJECT: 4002, STRING: 2001 }, withConnection: async (cb: (c: unknown) => unknown) => cb({ execute: async () => ({}) }) } as never;
    expect(await generateTableTypes(noRows)).toContain("import { defineTable, t }");
  });

  it("exportName: PascalCase, safe for a leading digit", () => {
    expect(exportName("SIM_ORDERS")).toBe("SimOrders");
    expect(exportName("ORDERS")).toBe("Orders");
    expect(exportName("A$B#C")).toBe("ABC");
    expect(exportName("2FA_KEYS")).toBe("T2faKeys");
  });
});
