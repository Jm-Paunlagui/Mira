/**
 * ============================================================================
 * typed/columns.ts — Column builders for defineTable() (Mira 2.1)
 * ============================================================================
 *
 * `t.money()`, `t.text(100).nullable()` … each builder carries two things:
 *   - at run time, the Oracle column it describes (`meta`), which
 *     defineTable().ddl() turns into the column spec createTable() takes;
 *   - at compile time only, the value type Mira returns for it (R), the
 *     value types it accepts in writes and filters (W), and three flags:
 *     nullable (N), has a DEFAULT (D), generated by Oracle (G).
 *
 * The value types follow what Mira 2.0.1+ actually returns:
 *   NUMBER with scale 0 / no scale → number
 *   NUMBER with a scale (money, decimal) → string (exact, money-safe)
 *   VARCHAR2 / CHAR / CLOB → string, BLOB / RAW → Buffer, DATE / TIMESTAMP → Date
 * ============================================================================
 */

/** What createTable() needs for one column, plus what the type layer needs. */
export interface ColumnMeta {
  /** Oracle type text, e.g. "NUMBER(19,4)" or "VARCHAR2(100)". */
  type: string;
  nullable: boolean;
  /** Raw SQL DEFAULT expression or number (trusted code, never user input). */
  default?: string | number;
  /** GENERATED ALWAYS AS IDENTITY: Oracle assigns it, an insert must not. */
  identity: boolean;
  primaryKey: boolean;
  /** Raw SQL CHECK condition (trusted code). */
  check?: string;
  references?: { table: string; column: string };
}

/**
 * A column. R = value read back, W = values accepted in writes / filters,
 * N = nullable, D = has a DEFAULT, G = generated by Oracle (identity).
 * The type parameters exist only for the compiler; `meta` is the run-time part.
 */
export class Column<R, W = R, N extends boolean = false, D extends boolean = false, G extends boolean = false> {
  declare readonly $read: R;
  declare readonly $write: W;
  declare readonly $nullable: N;
  declare readonly $hasDefault: D;
  declare readonly $generated: G;
  readonly meta: Readonly<ColumnMeta>;

  constructor(meta: ColumnMeta) {
    this.meta = Object.freeze({ ...meta });
  }

  private with<R2 = R, W2 = W, N2 extends boolean = N, D2 extends boolean = D, G2 extends boolean = G>(patch: Partial<ColumnMeta>): Column<R2, W2, N2, D2, G2> {
    return new Column<R2, W2, N2, D2, G2>({ ...this.meta, ...patch });
  }

  /** Allows NULL: reads may return null, inserts may leave it out. */
  nullable(): Column<R, W, true, D, G> {
    return this.with<R, W, true, D, G>({ nullable: true });
  }

  /** DEFAULT <expr> (raw SQL, e.g. "SYSTIMESTAMP" or "'active'"): inserts may leave it out. */
  default(expr: string | number): Column<R, W, N, true, G> {
    return this.with<R, W, N, true, G>({ default: expr });
  }

  /** PRIMARY KEY. */
  primaryKey(): Column<R, W, N, D, G> {
    return this.with({ primaryKey: true, nullable: false });
  }

  /** CHECK (<condition>) — raw SQL, trusted code only. */
  check(condition: string): Column<R, W, N, D, G> {
    return this.with({ check: condition });
  }

  /** FOREIGN KEY: REFERENCES table(column). `table` may be a defineTable() result. */
  references(table: string | { name: string }, column: string): Column<R, W, N, D, G> {
    return this.with({ references: { table: typeof table === "string" ? table : table.name, column } });
  }

  /** GENERATED ALWAYS AS IDENTITY: Oracle assigns the value, so inserts cannot set it. */
  identity(): Column<R, W, N, D, true> {
    return this.with<R, W, N, D, true>({ identity: true });
  }

  /** GENERATED BY DEFAULT AS IDENTITY: Oracle assigns a value unless the insert gives one. */
  identityByDefault(): Column<R, W, N, true, G> {
    return this.with<R, W, N, true, G>({ type: `${this.meta.type} GENERATED BY DEFAULT AS IDENTITY` });
  }
}

const col = <R, W = R>(type: string) => new Column<R, W>({ type, nullable: false, identity: false, primaryKey: false });

/** A positive integer spliced into a type: checked so a builder can never emit odd DDL. */
function size(name: string, n: unknown): number {
  if (!(Number.isInteger(n) && (n as number) > 0)) throw new TypeError(`[defineTable] t.${name} size must be a positive integer, got ${String(n)}.`);
  return n as number;
}

/** A NUMBER(precision, scale) column: scale 0 reads as number, a scale reads as an exact string. */
function number(): Column<number>;
function number(precision: number): Column<number>;
function number(precision: number, scale: 0): Column<number>;
function number(precision: number, scale: number): Column<string, string | number>;
function number(precision?: number, scale?: number): Column<number> | Column<string, string | number> {
  if (precision === undefined) return col<number>("NUMBER");
  size("number", precision);
  if (scale === undefined || scale === 0) return col<number>(scale === 0 ? `NUMBER(${precision},0)` : `NUMBER(${precision})`);
  if (!Number.isInteger(scale) || scale < 0 || scale > precision) throw new TypeError(`[defineTable] t.number scale must be an integer from 0 to the precision, got ${String(scale)}.`);
  return col<string, string | number>(`NUMBER(${precision},${scale})`);
}

/** Column builders for defineTable(). */
export const t = {
  /** NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY — Oracle assigns it. */
  id: () => col<number>("NUMBER").identity().primaryKey(),
  number,
  /** NUMBER(19,4): money, read back as an exact decimal string; writes take a string or number. */
  money: () => col<string, string | number>("NUMBER(19,4)"),
  /** NUMBER(precision, scale) with scale > 0, read back as an exact decimal string. */
  decimal: (precision: number, scale: number) => number(size("decimal", precision), size("decimal scale", scale)) as Column<string, string | number>,
  /** VARCHAR2(length) — `semantics: "char"` gives VARCHAR2(length CHAR). */
  text: (length: number, semantics?: "byte" | "char") => col<string>(`VARCHAR2(${size("text", length)}${semantics === "char" ? " CHAR" : ""})`),
  /** CHAR(length), blank-padded. */
  char: (length: number) => col<string>(`CHAR(${size("char", length)})`),
  /** CLOB — read back as a string (Mira 2.0.1+). */
  clob: () => col<string>("CLOB"),
  /** BLOB — read back as a Buffer (Mira 2.0.1+). */
  blob: () => col<Buffer>("BLOB"),
  /** DATE (date and time to the second). */
  date: () => col<Date>("DATE"),
  /** TIMESTAMP(precision), default precision 6. */
  timestamp: (precision?: number) => col<Date>(precision === undefined ? "TIMESTAMP" : `TIMESTAMP(${precision === 0 ? 0 : size("timestamp", precision)})`),
  /** TIMESTAMP(precision) WITH TIME ZONE. */
  timestampTz: (precision?: number) => col<Date>(precision === undefined ? "TIMESTAMP WITH TIME ZONE" : `TIMESTAMP(${precision === 0 ? 0 : size("timestampTz", precision)}) WITH TIME ZONE`),
  /**
   * Any other Oracle type, with the value type you name:
   * `t.raw<number>("BINARY_DOUBLE")`, `t.raw<Buffer>("RAW(16)")`.
   * The type text goes into DDL as is: trusted code only.
   */
  raw: <R, W = R>(oracleType: string) => col<R, W>(oracleType),
};

/** Any column, whatever its types. */
export type AnyColumn = Column<any, any, boolean, boolean, boolean>;
